void main() {
  String day = "Monday"; // Current day

  switch (day) {
    case "Monday":
      print("Start of the week!");
      break;
    case "Tuesday":
      print("Keep going!");
      break;
    case "Wednesday":
      print("Hump day!");
      break;
    case "Thursday":
      print("Almost there!");
      break;
    case "Friday":
      print("TGIF!");
      break;
    case "Saturday":
      print("Relax and enjoy!");
      break;
    case "Sunday":
      print("Rest and prepare.");
      break;
    default:
      print("Invalid day.");
  }
}
